from datasets import Dataset, load_dataset
import fitz
import os
import pymupdf

def extract_text_from_pdf(pdf_path):
    text_blocks = []
    with pymupdf.open(pdf_path) as doc:
        for page in doc:
            text = page.get_text("text").strip()
            if text:
                text_blocks.append(text)
    return text_blocks

pdf_texts = extract_text_from_pdf("/content/constitution_of_india.pdf")

import re
def split_paragraphs(pages):
    paragraphs = []
    for page_text in pages:
        # Split on double line breaks or long newlines
        chunks = re.split(r'\n\s*\n', page_text)
        for chunk in chunks:
            clean = chunk.strip()
            if len(clean) > 30:  # ignore too short lines
                paragraphs.append(clean)
    return paragraphs

paragraphs = split_paragraphs(pdf_texts)

data = [{"text": p} for p in paragraphs]

dataset = Dataset.from_list(data)

print(dataset)

model_name = "Qwen/Qwen2.5-1.5B"

from transformers import AutoTokenizer, AutoModelForCausalLM, Trainer, TrainingArguments, DataCollatorForLanguageModeling

tokenizer = AutoTokenizer.from_pretrained(model_name)

if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

def tokenize_fn(examples):
    tokens = tokenizer(examples["text"],truncation=True,padding="max_length",max_length=512)
    tokens["labels"] = tokens["input_ids"].copy()
    return tokens

tokenized = dataset.map(tokenize_fn, batched=True, remove_columns=["text"])

model = AutoModelForCausalLM.from_pretrained(model_name, device_map="auto")

for param in model.parameters():
    param.requires_grad = False

for name, param in model.named_parameters():
    if any(f"layers.{i}." in name for i in range(20, 24)):  # last 4 layers
        param.requires_grad = True
    if "lm_head" in name:
        param.requires_grad = True

# Verify how many parameters are trainable
trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
total = sum(p.numel() for p in model.parameters())
print(f"Trainable: {trainable/total*100:.2f}% of total parameters")

data_collator = DataCollatorForLanguageModeling(tokenizer=tokenizer, mlm=False)

os.environ["WANDB_DISABLED"] = "true"  # disable wandb
training_args = TrainingArguments(
    output_dir="./qwen",
    num_train_epochs=2,
    per_device_train_batch_size=2,
    gradient_accumulation_steps=4,
    learning_rate=1e-4,        # slightly higher since fewer params
    bf16=True,
    logging_steps=20,
    save_steps=200,
    save_total_limit=2,
    report_to="none"
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized,
    data_collator=data_collator
)

trainer.train()

trainer.save_model("./qwen_fine_tuned_without_lora")
print("model saved")

prompt = "Laws inconsistent with or in derogation of the fundamental rights"

inputs = tokenizer(prompt, return_tensors="pt").to("cuda")

outputs = model.generate(
    **inputs,
    max_new_tokens=100,
    temperature=0.4,
    top_p=0.9,
    do_sample=True,
    repetition_penalty=1.1
)

print(tokenizer.decode(outputs[0], skip_special_tokens=True))

